bool render_dashboard(const std::string& path, const Metrics& metrics,
                      const std::string& font_file) {
    if (!font_file.empty()) {
        FcConfigAppFontAddFile(nullptr,
            reinterpret_cast<const FcChar8*>(font_file.c_str()));
        FcConfigBuildFonts(nullptr);
    }

    cairo_surface_t* surface = cairo_image_surface_create(
        CAIRO_FORMAT_ARGB32, display_width, display_height);
    if (cairo_surface_status(surface) != CAIRO_STATUS_SUCCESS) {
        cairo_surface_destroy(surface);
        return false;
    }
    cairo_t* cr = cairo_create(surface);
    cairo_set_antialias(cr, CAIRO_ANTIALIAS_BEST);

    cairo_pattern_t* background = cairo_pattern_create_linear(0, 0, display_width, 0);
    cairo_pattern_add_color_stop_rgb(background, 0.0, 0.018, 0.025, 0.045);
    cairo_pattern_add_color_stop_rgb(background, 0.55, 0.035, 0.045, 0.070);
    cairo_pattern_add_color_stop_rgb(background, 1.0, 0.015, 0.020, 0.035);
    cairo_set_source(cr, background);
    cairo_paint(cr);
    cairo_pattern_destroy(background);

    // Asset-free accent lines make the default dashboard recognizable while
    // keeping every rendered pixel generated by this program.
    cairo_pattern_t* accent = cairo_pattern_create_linear(0, 0, 900, 0);
    cairo_pattern_add_color_stop_rgba(accent, 0.0, 1.0, 0.18, 0.02, 0.0);
    cairo_pattern_add_color_stop_rgba(accent, 0.45, 1.0, 0.35, 0.02, 0.85);
    cairo_pattern_add_color_stop_rgba(accent, 1.0, 1.0, 0.58, 0.02, 0.0);
    cairo_set_source(cr, accent);
    cairo_set_line_width(cr, 3);
    cairo_move_to(cr, 42, 64);
    cairo_line_to(cr, 876, 64);
    cairo_stroke(cr);
    cairo_pattern_destroy(accent);

    std::time_t raw_time = std::time(nullptr);
    std::tm now{};
    localtime_r(&raw_time, &now);
    std::ostringstream clock;
    clock << std::put_time(&now, "%H:%M:%S");
    std::ostringstream date;
    date << std::put_time(&now, "%a  %d %b %Y");

    fitted_text(cr, "SYSTEM STATUS", 42, 91, 780, 54, 28, false,
                1.0, 0.40, 0.03);
    fitted_text(cr, clock.str(), 42, 148, 820, 130, 96, false, 1, 1, 1);
    fitted_text(cr, date.str(), 45, 294, 760, 54, 25, false,
                0.66, 0.69, 0.76, CAIRO_FONT_WEIGHT_NORMAL);
    fitted_text(cr, "COUGAR CFV235 LCD", 45, 361, 760, 42, 20, false,
                0.39, 0.42, 0.49, CAIRO_FONT_WEIGHT_NORMAL);

    metric_card(cr, 1010, "CPU", metrics.cpu_temperature, metrics.cpu_load);
    metric_card(cr, 1462, "GPU", metrics.gpu_temperature, metrics.gpu_load);

    cairo_destroy(cr);
    const cairo_status_t status = cairo_surface_write_to_png(surface, path.c_str());
    cairo_surface_destroy(surface);
    return status == CAIRO_STATUS_SUCCESS;
}

