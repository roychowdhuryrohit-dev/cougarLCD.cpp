constexpr double pi = 3.14159265358979323846;

void color(cairo_t* cr, double r, double g, double b, double a = 1.0) {
    cairo_set_source_rgba(cr, r, g, b, a);
}

void rounded_rectangle(cairo_t* cr, double x, double y, double width,
                       double height, double radius) {
    const double right = x + width;
    const double bottom = y + height;
    cairo_new_sub_path(cr);
    cairo_arc(cr, right - radius, y + radius, radius, -pi / 2, 0);
    cairo_arc(cr, right - radius, bottom - radius, radius, 0, pi / 2);
    cairo_arc(cr, x + radius, bottom - radius, radius, pi / 2, pi);
    cairo_arc(cr, x + radius, y + radius, radius, pi, 3 * pi / 2);
    cairo_close_path(cr);
}

void fitted_text(cairo_t* cr, const std::string& value, double x, double y,
                 double width, double height, double preferred_size,
                 bool centered, double r, double g, double b,
                 cairo_font_weight_t weight = CAIRO_FONT_WEIGHT_BOLD) {
    cairo_select_font_face(cr, "DejaVu Sans", CAIRO_FONT_SLANT_NORMAL, weight);
    double size = preferred_size;
    cairo_text_extents_t extents{};
    do {
        cairo_set_font_size(cr, size);
        cairo_text_extents(cr, value.c_str(), &extents);
        if (extents.width <= width && extents.height <= height) break;
        size -= 1.0;
    } while (size > 10.0);
    color(cr, r, g, b);
    const double text_x = centered
        ? x + (width - extents.width) / 2.0 - extents.x_bearing
        : x - extents.x_bearing;
    const double text_y = y + (height - extents.height) / 2.0 - extents.y_bearing;
    cairo_move_to(cr, text_x, text_y);
    cairo_show_text(cr, value.c_str());
}

void metric_card(cairo_t* cr, double x, const char* label,
                 unsigned temperature, unsigned load) {
    constexpr double y = 42;
    constexpr double width = 390;
    constexpr double height = 378;
    constexpr double cx_offset = width / 2;
    constexpr double cy = 228;
    constexpr double radius = 137;

    rounded_rectangle(cr, x, y, width, height, 34);
    color(cr, 0.055, 0.067, 0.09, 0.90);
    cairo_fill_preserve(cr);
    color(cr, 0.23, 0.26, 0.32, 0.75);
    cairo_set_line_width(cr, 2);
    cairo_stroke(cr);

    cairo_set_line_cap(cr, CAIRO_LINE_CAP_ROUND);
    cairo_set_line_width(cr, 28);
    color(cr, 0.20, 0.22, 0.27, 1.0);
    cairo_arc(cr, x + cx_offset, cy, radius, -pi / 2, 3 * pi / 2);
    cairo_stroke(cr);
    if (temperature > 0) {
        const double fraction = std::min(temperature, 100u) / 100.0;
        cairo_pattern_t* arc = cairo_pattern_create_linear(x + 40, 0, x + width, 0);
        cairo_pattern_add_color_stop_rgb(arc, 0, 1.0, 0.29, 0.02);
        cairo_pattern_add_color_stop_rgb(arc, 1, 1.0, 0.68, 0.05);
        cairo_set_source(cr, arc);
        cairo_arc(cr, x + cx_offset, cy, radius, -pi / 2,
                  -pi / 2 + 2 * pi * fraction);
        cairo_stroke(cr);
        cairo_pattern_destroy(arc);
    }

    fitted_text(cr, label, x + 40, 82, width - 80, 56, 38, true, 1, 1, 1);
    const std::string temp = temperature
        ? std::to_string(temperature) + " \xC2\xB0" "C"
        : "-- \xC2\xB0" "C";
    fitted_text(cr, temp, x + 35, 173, width - 70, 95, 56, true, 1, 1, 1);
    fitted_text(cr, "LOAD " + std::to_string(load) + "%",
                x + 70, 287, width - 140, 48, 18, true,
                1.0, 0.42, 0.04);
}

